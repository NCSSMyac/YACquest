export type GlyphName = keyof typeof GLYPHS;

export function PixelGlyph({ name, size = 24, className }: { name: GlyphName; size?: number; className?: string }) {
  const rects: JSX.Element[] = [];
  GLYPHS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch === '#' || ch === '+') {
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={end - x + 0.02} height={1.02} fill={ch === '#' ? 'currentColor' : 'var(--glyph-accent, var(--gold-500))'} />);
      }
      x = end;
    }
  });
  return (
    <svg viewBox="0 0 16 16" width={size} height={size} className={`pixel-glyph ${className ?? ''}`} shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      {rects}
    </svg>
  );
}
